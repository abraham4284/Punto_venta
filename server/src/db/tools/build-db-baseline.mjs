import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { baselineFiles } from "./db-baseline.manifest.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const dbRoot = path.resolve(__dirname, "..");
const generatedPath = path.join(dbRoot, "generated", "cajora_v1_0_full.sql");

function normalizeSql(content) {
  return content.replace(/\r\n/g, "\n").replace(/\r/g, "\n").trimEnd();
}

function createSection(filePath, content) {
  return [
    "/* ============================================================",
    `   BEGIN: ${filePath}`,
    "   ============================================================ */",
    "",
    normalizeSql(content),
    "",
    "/* ============================================================",
    `   END: ${filePath}`,
    "   ============================================================ */",
  ].join("\n");
}

export async function buildBaselineSql() {
  const sections = [];

  for (const filePath of baselineFiles) {
    const absolutePath = path.join(dbRoot, filePath);
    const content = await readFile(absolutePath, "utf8");
    sections.push(createSection(filePath, content));
  }

  return [
    "/*",
    "  GENERATED FILE - DO NOT EDIT MANUALLY",
    "",
    "  Source of truth:",
    "  - schema/",
    "  - seeds/",
    "  - procedures/",
    "  - publications/",
    "",
    "  Generated by:",
    "  tools/build-db-baseline.mjs",
    "",
    "  Target:",
    "  an already selected EMPTY database.",
    "*/",
    "",
    sections.join("\n\n"),
    "",
  ].join("\n");
}

async function main() {
  const sql = await buildBaselineSql();
  await mkdir(path.dirname(generatedPath), { recursive: true });
  await writeFile(generatedPath, sql, "utf8");

  const hash = createHash("sha256").update(sql, "utf8").digest("hex");
  console.log(`Generated ${path.relative(dbRoot, generatedPath).replace(/\\/g, "/")}`);
  console.log(`SHA-256 cajora_v1_0_full.sql: ${hash}`);
}

if (process.argv[1] === __filename) {
  main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
